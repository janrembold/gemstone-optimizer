import { build } from 'vite';
import { mkdirSync, writeFileSync } from 'node:fs';

// The same application and optical worker as the HTTP build, bundled as classic JS.
// Classic local scripts and Blob workers can start from file:// without module fetches.
const result = await build({
  configFile: false,
  worker: { format: 'iife' },
  build: {
    write: false,
    minify: 'esbuild',
    lib: {
      entry: 'js/app.js',
      name: 'GemCutLab',
      formats: ['iife'],
    },
  },
});
const output = (Array.isArray(result) ? result : [result]).flatMap((bundle) => bundle.output);
const entry = output.find((file) => file.type === 'chunk' && file.isEntry);
if (!entry || output.some((file) => file.type === 'chunk' && file !== entry)) {
  throw new Error('Standalone build must contain exactly one self-contained JavaScript entry');
}
mkdirSync('standalone', { recursive: true });
writeFileSync(
  'standalone/app.js',
  '// Generated by npm run build:standalone. Do not edit.\n' + entry.code,
);
